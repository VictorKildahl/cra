#!/usr/bin/env python3
"""Writes Sources/Cra/UI/Sidebar/EmojiCatalog+Data.swift from Unicode's emoji-test.txt.

    scripts/make-emoji-catalog.py <path to emoji-test.txt>

Keeps fully-qualified emoji up to Emoji 15.0 (the set Arc 1.171's picker shows) without skin-tone
variants, in Unicode's order, grouped like the category bar of Arc's space icon picker (People & Body
joins Smileys, Component is dropped).
"""
import sys

GROUPS = [
    ("smileys", ["Smileys & Emotion", "People & Body"]),
    ("nature", ["Animals & Nature"]),
    ("food", ["Food & Drink"]),
    ("activities", ["Activities"]),
    ("travel", ["Travel & Places"]),
    ("objects", ["Objects"]),
    ("symbols", ["Symbols"]),
    ("flags", ["Flags"]),
]
TONES = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}
MAX_VERSION = 15.0

src = sys.argv[1]
version = "?"
by_group = {}
group = None
for line in open(src, encoding="utf-8"):
    if line.startswith("# Version:"):
        version = line.split(":", 1)[1].strip()
    if line.startswith("# group:"):
        group = line.split(":", 1)[1].strip()
        continue
    if not line.strip() or line.startswith("#") or "; fully-qualified" not in line:
        continue
    codes, rest = line.split(";", 1)
    cps = [int(c, 16) for c in codes.split()]
    if TONES & set(cps):
        continue
    emoji, name = rest.split("#", 1)[1].strip().split(" ", 1)
    tag, name = name.split(" ", 1)  # "E15.0 grinning face"
    if float(tag[1:]) > MAX_VERSION:
        continue
    by_group.setdefault(group, []).append((emoji, name.replace("\\", "").replace('"', "")))

out = [
    "// Generated by scripts/make-emoji-catalog.py from Unicode emoji-test.txt %s (emoji up to %s). Do not edit." % (version, MAX_VERSION),
    "",
    "extension EmojiCatalog {",
    "    /// Category, then one \"<emoji> <name>\" per line.",
    "    static let data: [(String, String)] = [",
]
for key, names in GROUPS:
    rows = [f"{e} {n}" for g in names for e, n in by_group.get(g, [])]
    body = "\n".join(rows)
    out.append(f'        ("{key}", """\n{body}\n"""),')
out += ["    ]", "}", ""]
open("Sources/Cra/UI/Sidebar/EmojiCatalog+Data.swift", "w", encoding="utf-8").write("\n".join(out))
print({k: sum(len(by_group.get(g, [])) for g in v) for k, v in GROUPS})
